import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const base = process.env.OFFICE_TEST_URL ?? 'http://127.0.0.1:4391/';
const evidence = process.env.OFFICE_TEST_EVIDENCE ?? '.omo/evidence/academic-release';
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on('pageerror', error => errors.push(error.message));
  const settle = () => page.waitForTimeout(1800);
  const ready = () => page.locator('.studio[data-room-ready="true"]').waitFor({ timeout: 120000 });
  const menu = page.locator('.office-guided button');
  await page.goto(base);
  await ready(); await settle();
  assert.equal(await page.locator('.studio').getAttribute('data-guided'), '1');
  assert.deepEqual(await menu.allTextContents(), ['Overview', 'Front', 'CV', 'Talks', 'Research', 'UBE & Teaching']);
  await page.screenshot({ path: `${evidence}/front.png` });
  await menu.nth(2).click(); await settle();
  assert.equal(await page.locator('.studio').getAttribute('data-selected'), 'ai');
  assert(await menu.last().isVisible());
  await page.screenshot({ path: `${evidence}/cv.png` });
  await menu.nth(3).click();
  await page.locator('.tv-screen-reader[data-active="true"]').waitFor(); await settle();
  await page.screenshot({ path: `${evidence}/talks.png` });
  await page.keyboard.press('Escape'); await settle();
  assert.equal(await page.locator('.studio').getAttribute('data-guided'), '1');
  assert.equal(await page.locator('.studio').getAttribute('data-selected'), null);
  await page.goto(new URL('?exhibit=research&stage=approach', base).href);
  await ready(); await settle();
  await page.mouse.click(720, 460);
  await page.locator('.research-book-index').waitFor(); await settle();
  const layout = await page.evaluate(() => {
    const surface = document.querySelector('.research-book-surface');
    const r = surface.getBoundingClientRect();
    return { inBook: !!surface.closest('[style*="matrix3d"]'), dialog: !!document.querySelector('dialog[open]'), image: document.querySelector('.research-book-preview img').naturalWidth, rect: r.toJSON(), categories: [...document.querySelectorAll('.research-book-category')].map(e => e.textContent), dropdowns: document.querySelectorAll('.research-book-index select').length };
  });
  assert(layout.inBook && !layout.dialog && layout.image > 0);
  assert.equal(layout.dropdowns, 0);
  assert.equal(layout.categories.length, 31);
  assert(layout.rect.x > 0 && layout.rect.y > 0 && layout.rect.bottom < 900);
  await page.screenshot({ path: `${evidence}/research.png` });
  const first = await page.locator('.research-folio').getAttribute('data-active-paper');
  await page.locator('.research-book-next').click(); await settle();
  assert.notEqual(await page.locator('.research-folio').getAttribute('data-active-paper'), first);
  await page.locator('.research-book-topics button').nth(2).click(); await settle();
  await page.locator('.research-book-authors button').nth(3).click(); await settle();
  assert.equal(await page.locator('.research-book-count strong').textContent(), '4');
  await page.locator('.research-book-topics button').nth(1).click(); await settle();
  await page.locator('.research-book-authors button').nth(1).click(); await settle();
  assert.equal(await page.locator('.research-book-topics button[aria-pressed="true"]').count(), 2);
  assert.equal(await page.locator('.research-book-authors button[aria-pressed="true"]').count(), 2);
  await page.locator('.research-book-topics button').first().click(); await settle();
  await page.locator('.research-book-authors button').first().click(); await settle();
  assert.equal(await page.locator('.research-book-count strong').textContent(), '31');
  await page.keyboard.press('Escape'); await settle();
  assert.equal(await page.locator('.research-book-surface').count(), 0);
  await page.goto(base); await ready(); await settle();
  await menu.last().click(); await settle();
  await page.screenshot({ path: `${evidence}/teaching.png` });
  await page.goto(new URL('?exhibit=education&detail=%2Fworkshops%2Fcadaver', base).href);
  await ready();
  await page.locator('.tv-teaching').waitFor(); await settle();
  assert.equal(await page.locator('.tv-teaching nav button').count(), 4);
  await page.locator('.tv-teaching nav button').nth(1).click(); await settle();
  assert.equal(await page.locator('.tv-teaching nav button').nth(1).getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: `${evidence}/teaching-content.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base); await ready(); await settle();
  assert.equal(await page.locator('.studio').getAttribute('data-guided'), '1');
  await menu.nth(2).click(); await settle();
  assert(await menu.last().isVisible());
  await page.screenshot({ path: `${evidence}/mobile-cv.png` });
  assert.deepEqual(errors, []);
  console.log('PASS: Front default, six menu destinations, CV menu, Talks escape, desk book and original page, categories, filtered page turns, multi-selection/reset, teaching switch, mobile entry/CV, no runtime exceptions.');
} finally { await browser.close(); }
